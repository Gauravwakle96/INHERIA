import { expect, test } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

test('administrator revokes project access with confirmation; incoming account loses project knowledge', async ({ page, browser }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Open judge workspace' }).click();
  await expect(page.getByRole('combobox', { name: 'Active project' })).toBeVisible();
  const pid = await page.getByRole('combobox', { name: 'Active project' }).inputValue();
  await page.goto('/team');
  await page.getByRole('button', { name: 'Invite member', exact: true }).click();
  const invite = page.getByRole('dialog', { name: 'Invite a project member' });
  await invite.getByLabel('Name', { exact: true }).fill('Temporary Judge Member');
  await invite.getByLabel('Email', { exact: true }).fill(`temporary-${Date.now()}@example.com`);
  await invite.getByLabel('Role title').fill('Incoming engineer');
  await invite.getByRole('button', { name: 'Create invitation' }).click();
  const share = page.getByRole('dialog', { name: 'Share the invitation privately' });
  const link = await share.getByLabel('One-time invitation link').inputValue();
  const incomingContext = await browser.newContext();
  const incoming = await incomingContext.newPage();
  await incoming.goto(link);
  await incoming.getByLabel('Your new password').fill('temporary-e2e-password');
  await incoming.getByRole('button', { name: 'Accept invitation' }).click();
  await expect(incoming.getByRole('heading', { name: 'Knowledge owners' })).toBeVisible();
  expect((await incoming.request.get(`/api/projects/${pid}/sources`)).status()).toBe(200);
  await share.getByRole('button', { name: 'Close dialog' }).click();
  await page.reload();
  const memberRow = page.locator('.transfer-row').filter({ has: page.getByText('Temporary Judge Member', { exact: true }) });
  await memberRow.getByRole('button', { name: 'Revoke project access' }).click();
  const confirm = page.getByRole('dialog', { name: 'Revoke project access', exact: true });
  await confirm.getByLabel('Reason for this access decision').fill('Temporary judge account review completed. Remove project knowledge access.');
  await confirm.getByRole('button', { name: 'Confirm revocation' }).click();
  await expect(confirm).not.toBeVisible();
  expect((await incoming.request.get(`/api/projects/${pid}/sources`)).status()).toBe(404);
  expect((await incoming.request.get(`/api/projects/${pid}/chat/conversations`)).status()).toBe(404);
  await page.setViewportSize({ width: 390, height: 900 });
  await page.getByRole('button', { name: 'Switch to day mode' }).click();
  await expect(page.getByRole('heading', { name: 'Handover knowledge access' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  const axe = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
  expect(axe.violations.map(v => v.id)).toEqual([]);
  await incomingContext.close();
});
